#!/usr/bin/env node
/**
 * Submit changed/new URLs to Bing Webmaster's SubmitUrlBatch API: the same
 * "request indexing" action as clicking it manually in Bing Webmaster Tools,
 * just scriptable. Use this (not just IndexNow) whenever content actually
 * changes, so Bing prioritizes a recrawl instead of waiting on its own
 * schedule. See docs/reference/SERVER_REFERENCE.md "Bing priority reindex".
 *
 * Usage:
 *   node scripts/submit-bing.mjs /blog/new-post-slug /compare/new-item-slug
 *   node scripts/submit-bing.mjs https://thecrawli.com/pricing
 *
 * Accepts either site-relative paths or full URLs. Requires BING_WMT_API_KEY
 * in .env (Bing Webmaster Tools → Settings → API Access, tied to the
 * account, must be generated by a human, not by Claude).
 */

import dotenv from 'dotenv';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.join(__dirname, '..', '.env');
const env = dotenv.parse(fs.readFileSync(envPath, 'utf8'));

const API_KEY = env.BING_WMT_API_KEY;
// Bing authorizes the request against the verified property, and rejects URLs
// that aren't on it. NEXT_PUBLIC_SITE_URL is localhost in a dev .env, which
// makes Bing 400 with NotAuthorized, so ignore localhost/empty values and
// force the production domain. A non-localhost env value still wins (e.g. a
// staging property), matching how this runs on the server.
const RAW_SITE = env.NEXT_PUBLIC_SITE_URL || '';
const SITE_URL = (!RAW_SITE || /localhost|127\.0\.0\.1/.test(RAW_SITE))
  ? 'https://thecrawli.com'
  : RAW_SITE.replace(/\/$/, '');

const inputs = process.argv.slice(2);

if (!API_KEY) {
  console.error('❌ BING_WMT_API_KEY not set in .env');
  process.exit(1);
}
if (inputs.length === 0) {
  console.error('Usage: node scripts/submit-bing.mjs <path-or-url> [more...]');
  console.error('  e.g. node scripts/submit-bing.mjs /blog/my-new-post /compare/my-new-item');
  process.exit(1);
}

const urlList = inputs.map((u) => (u.startsWith('http') ? u : `${SITE_URL}${u.startsWith('/') ? u : `/${u}`}`));

console.log(`\n📤 Submitting ${urlList.length} URL(s) to Bing...\n`);
urlList.forEach((u) => console.log(`  ${u}`));

const submitRes = await fetch(
  `https://ssl.bing.com/webmaster/api.svc/json/SubmitUrlbatch?apikey=${API_KEY}`,
  {
    method: 'POST',
    headers: { 'Content-Type': 'application/json; charset=utf-8' },
    body: JSON.stringify({ siteUrl: SITE_URL, urlList }),
  },
);
const submitBody = await submitRes.json();

if (!submitRes.ok || submitBody.errorHResult) {
  console.error(`\n❌ Submission failed: HTTP ${submitRes.status}`, submitBody);
  process.exit(1);
}
console.log('\n✅ Submitted (Bing returns {d:null} on success for this endpoint).');

const quotaRes = await fetch(
  `https://ssl.bing.com/webmaster/api.svc/json/GetUrlSubmissionQuota?apikey=${API_KEY}&siteUrl=${encodeURIComponent(SITE_URL)}`,
);
const quotaBody = await quotaRes.json();
const quota = quotaBody?.d;
if (quota) {
  console.log(`\n📊 Remaining quota (daily: ${quota.DailyQuota}, monthly: ${quota.MonthlyQuota})`);
}
console.log();
